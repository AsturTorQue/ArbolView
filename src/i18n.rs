//! Interface languages. Each entry: key, then Spanish, English, Portuguese, French.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Es,
    En,
    Pt,
    Fr,
}

impl Lang {
    pub const ALL: [Lang; 4] = [Lang::Es, Lang::En, Lang::Pt, Lang::Fr];

    pub fn native_name(self) -> &'static str {
        match self {
            Lang::Es => "Español",
            Lang::En => "English",
            Lang::Pt => "Português",
            Lang::Fr => "Français",
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::Es => "es",
            Lang::En => "en",
            Lang::Pt => "pt",
            Lang::Fr => "fr",
        }
    }

    pub fn from_code(c: &str) -> Option<Lang> {
        let c = c.to_lowercase();
        Lang::ALL.into_iter().find(|l| c.starts_with(l.code()))
    }

    /// From $LANGUAGE / $LC_ALL / $LANG; Spanish when nothing matches.
    pub fn from_env() -> Lang {
        for v in ["LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"] {
            if let Ok(s) = std::env::var(v) {
                if let Some(l) = Lang::from_code(&s) {
                    return l;
                }
            }
        }
        Lang::Es
    }

    fn idx(self) -> usize {
        self as usize
    }
}

